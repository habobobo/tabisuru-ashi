-- Run once in a new Supabase project. No private travel records belong in GitHub.
create table public.allowed_users (
  email text primary key check (email=lower(btrim(email)) and length(email)<=254),
  created_at timestamptz not null default now()
);
alter table public.allowed_users enable row level security;
revoke all on public.allowed_users from anon, authenticated;

create function public.is_admitted() returns boolean
language sql stable security definer set search_path=''
as $$ select auth.uid() is not null and exists (
  select 1 from public.allowed_users where email=lower(auth.jwt()->>'email')
) $$;
revoke all on function public.is_admitted() from public;
grant execute on function public.is_admitted() to authenticated;

create table public.city_catalog (id text primary key);

create function public.partial_date_start(v text) returns date
language plpgsql immutable set search_path=''
as $$
declare y integer; m integer; d integer;
begin
  if v='' then return null; end if;
  if v !~ '^\d{4}(-\d{2})?(-\d{2})?$' then raise exception 'Invalid date'; end if;
  y:=split_part(v,'-',1)::integer;
  m:=coalesce(nullif(split_part(v,'-',2),''),'1')::integer;
  d:=coalesce(nullif(split_part(v,'-',3),''),'1')::integer;
  if y<1900 or y>2100 then raise exception 'Invalid year'; end if;
  return make_date(y,m,d);
end $$;
create function public.partial_date_end(v text) returns date
language sql immutable set search_path=''
as $$ select case when v='' then null when length(v)=4 then (public.partial_date_start(v)+interval '1 year -1 day')::date when length(v)=7 then (public.partial_date_start(v)+interval '1 month -1 day')::date else public.partial_date_start(v) end $$;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade default auth.uid(),
  name text not null default '我的足迹' check(length(btrim(name)) between 1 and 40),
  updated_at bigint not null default (extract(epoch from now())*1000)::bigint
);
create table public.experiences (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  city_id text not null references public.city_catalog(id),
  kind text not null check(kind in ('visit','stay','live')),
  start_date text not null default '',
  end_date text not null default '',
  ongoing boolean not null default false,
  note text not null default '' check(length(note)<=1000),
  updated_at bigint not null default (extract(epoch from now())*1000)::bigint,
  check(not ongoing or end_date=''),
  check(public.partial_date_start(start_date) is null or public.partial_date_end(end_date) is null or public.partial_date_start(start_date)<=public.partial_date_end(end_date))
);
-- Validate each date even when the other date is empty.
alter table public.experiences add check(start_date='' or public.partial_date_start(start_date) is not null);
alter table public.experiences add check(end_date='' or public.partial_date_start(end_date) is not null);
create index experiences_owner on public.experiences(owner_id,updated_at desc);
create table public.shares (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade default auth.uid(),
  viewer_email text not null check(viewer_email=lower(btrim(viewer_email)) and length(viewer_email)<=254 and viewer_email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
  created_at timestamptz not null default now(),
  unique(owner_id,viewer_email)
);
create index shares_viewer on public.shares(viewer_email);

alter table public.city_catalog enable row level security;
alter table public.profiles enable row level security;
alter table public.experiences enable row level security;
alter table public.shares enable row level security;
revoke all on public.city_catalog,public.profiles,public.experiences,public.shares from anon;
grant select on public.city_catalog to authenticated;
grant select,insert,update,delete on public.profiles,public.experiences,public.shares to authenticated;

create policy catalog_read on public.city_catalog for select to authenticated using(public.is_admitted());
create policy shares_read on public.shares for select to authenticated using(public.is_admitted() and (owner_id=auth.uid() or viewer_email=lower(auth.jwt()->>'email')));
create policy shares_insert on public.shares for insert to authenticated with check(public.is_admitted() and owner_id=auth.uid());
create policy shares_delete on public.shares for delete to authenticated using(public.is_admitted() and owner_id=auth.uid());
-- Sharing changes require deleting and creating a grant, never editing another grant.
revoke update on public.shares from authenticated;

create policy profiles_read on public.profiles for select to authenticated using(public.is_admitted() and (id=auth.uid() or exists(select 1 from public.shares s where s.owner_id=profiles.id and s.viewer_email=lower(auth.jwt()->>'email'))));
create policy profiles_insert on public.profiles for insert to authenticated with check(public.is_admitted() and id=auth.uid());
create policy profiles_update on public.profiles for update to authenticated using(public.is_admitted() and id=auth.uid()) with check(public.is_admitted() and id=auth.uid());

create policy experiences_read on public.experiences for select to authenticated using(public.is_admitted() and (owner_id=auth.uid() or exists(select 1 from public.shares s where s.owner_id=experiences.owner_id and s.viewer_email=lower(auth.jwt()->>'email'))));
create policy experiences_insert on public.experiences for insert to authenticated with check(public.is_admitted() and owner_id=auth.uid());
create policy experiences_update on public.experiences for update to authenticated using(public.is_admitted() and owner_id=auth.uid()) with check(public.is_admitted() and owner_id=auth.uid());
create policy experiences_delete on public.experiences for delete to authenticated using(public.is_admitted() and owner_id=auth.uid());

